CREATE TABLE players (
  id TEXT PRIMARY KEY,
  secret_hash TEXT NOT NULL,
  name_seed INTEGER NOT NULL,
  avatar TEXT NOT NULL,
  chips INTEGER NOT NULL DEFAULT 5000 CHECK (chips >= 0),
  xp INTEGER NOT NULL DEFAULT 0,
  level INTEGER NOT NULL DEFAULT 1,
  games INTEGER NOT NULL DEFAULT 0,
  wins INTEGER NOT NULL DEFAULT 0,
  created INTEGER NOT NULL,
  daily_at INTEGER NOT NULL DEFAULT 0,
  streak INTEGER NOT NULL DEFAULT 0,
  bail_at INTEGER NOT NULL DEFAULT 0,
  roll_day INTEGER NOT NULL DEFAULT 0,
  rolls INTEGER NOT NULL DEFAULT 0,
  week INTEGER NOT NULL DEFAULT 0,
  week_won INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE friends (
  a TEXT NOT NULL,
  b TEXT NOT NULL,
  state TEXT NOT NULL,
  PRIMARY KEY (a, b)
);
CREATE INDEX friends_b ON friends (b);

CREATE TABLE chip_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  player TEXT NOT NULL,
  delta INTEGER NOT NULL,
  reason TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE INDEX chip_log_player ON chip_log (player, at);
